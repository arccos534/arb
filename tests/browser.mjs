import { chromium } from 'playwright';
import { mkdtemp, rm } from 'node:fs/promises';
import path from 'node:path';
import { tmpdir } from 'node:os';
import { spawn } from 'node:child_process';
import assert from 'node:assert/strict';

const directory=await mkdtemp(path.join(tmpdir(),'arbitrage-browser-'));
const port=4329;
const child=spawn(process.execPath,['dist/server.js'],{cwd:process.cwd(),env:{...process.env,DATA_DIR:directory,WEB_PORT:String(port),OBSERVER_AUTOSTART:'false',EXECUTION_PROFILE:'true',LOG_LEVEL:'silent'},stdio:['ignore','pipe','pipe'],windowsHide:true});
let output='';child.stderr.on('data',b=>output+=b);child.stdout.on('data',b=>output+=b);
let browser;
try{
  for(let i=0;i<80;i++){try{if((await fetch(`http://127.0.0.1:${port}/api/health`)).ok)break;}catch{}await new Promise(r=>setTimeout(r,100));}
  browser=await chromium.launch({channel:'msedge',headless:true});
  const page=await browser.newPage({viewport:{width:1440,height:1100}});
  const errors=[],posts=[];page.on('pageerror',e=>errors.push(e.message));page.on('request',r=>{if(r.method()==='POST')posts.push(r.postData()??'');});
  let catalogueFailed=true;
  const networkStatusRoute=async route=>{
    const response=await route.fetch();const state=await response.json();
    if(catalogueFailed){state.feed.discoveryError='TypeError: fetch failed';state.feed.discoveryRetrying=true;}
    await route.fulfill({response,json:state});
  };
  await page.route('**/api/state?source=live',networkStatusRoute);
  await page.goto(`http://127.0.0.1:${port}`);
  assert.equal(await page.locator('html').getAttribute('data-theme'),'dark');
  await page.locator('[data-theme-toggle]').click();
  assert.equal(await page.locator('html').getAttribute('data-theme'),'light');
  await page.reload();
  assert.equal(await page.locator('html').getAttribute('data-theme'),'light');
  await page.locator('[data-theme-toggle]').click();
  assert.equal(await page.locator('html').getAttribute('data-theme'),'dark');
  await page.locator('[role="status"]').filter({hasText:'fetch failed'}).waitFor();
  assert.ok((await page.locator('[role="status"]').filter({hasText:'fetch failed'}).textContent()).includes('Повторная загрузка уже идёт'));
  assert.equal(await page.locator('.banner-error').count(),0);
  catalogueFailed=false;
  await page.locator('[role="status"]').filter({hasText:'fetch failed'}).waitFor({state:'detached'});
  await page.unroute('**/api/state?source=live',networkStatusRoute);
  await page.getByRole('heading',{name:'Контрольная панель'}).waitFor();
  assert.ok(await page.locator('[data-market-row]').count()<=10);
  await page.getByLabel('Источник данных').selectOption('demo');
  await page.getByTestId('run-demo').waitFor();
  await page.getByTestId('run-demo').click();
  await page.locator('#skip-review-toggle').check();
  await page.waitForFunction(async()=> (await(await fetch('/api/state?source=demo')).json()).state.settings.skipManualReview===true);
  await page.locator('#skip-review-toggle').uncheck();
  await page.waitForFunction(async()=> (await(await fetch('/api/state?source=demo')).json()).state.settings.skipManualReview===false);
  await page.waitForFunction(()=>document.querySelector('[data-testid="realized-pnl"]')?.textContent?.includes('+'),{timeout:30000});
  await page.getByRole('link',{name:'Сделки',exact:true}).click();
  await page.getByText('Рассчитана',{exact:true}).waitFor();
  await page.getByRole('button',{name:'Детали ↗'}).first().click();
  await page.getByRole('heading',{name:'Детали виртуальной сделки'}).waitFor();
  const execution=page.getByTestId('trade-execution');
  assert.ok((await execution.textContent()).includes('Стоимость покупки при сигнале: $'));
  assert.ok((await execution.textContent()).includes('Повторная стоимость покупки: $'));
  assert.ok((await execution.textContent()).includes('Возраст получения:'));
  assert.ok((await page.getByTestId('execution-counters').textContent()).includes('отмены до покупки: 0'));
  await page.getByRole('button',{name:'Закрыть',exact:true}).click();
  await page.getByRole('link',{name:'Подключения',exact:true}).click();
  const secret='test-secret-DO-NOT-STORE';
  await page.locator('[data-connection="Polymarket"] input').first().fill(secret);
  await page.locator('[data-connection="Polymarket"]').getByRole('button',{name:'Проверить макет'}).click();
  assert.equal(await page.locator('[data-connection="Polymarket"] input').first().inputValue(),'');
  assert.ok(posts.every(body=>!body.includes(secret)));
  await page.getByRole('link',{name:'Обзор',exact:true}).click();
  await page.getByTestId('trading-toggle').click();
  await page.getByRole('link',{name:'Параметры стратегии',exact:true}).click();
  await page.locator('[name="lossLimit"]').fill('20');
  await page.locator('[name="skipManualReview"]').check();
  await page.getByRole('button',{name:'Сохранить параметры',exact:true}).click();
  await page.waitForFunction(()=>document.querySelector('[name="lossLimit"]')?.value==='20');
  const settingsState=await (await page.request.get(`http://127.0.0.1:${port}/api/state?source=demo`)).json();
  assert.equal(settingsState.state.settings.skipManualReview,true);
  await page.reload();
  await page.getByLabel('Источник данных').selectOption('demo');
  await page.locator('[name="skipManualReview"]:checked').waitFor();
  await page.getByRole('link',{name:'Журнал событий',exact:true}).click();
  await page.getByRole('button',{name:'Показать файлы'}).click();
  await page.locator('.file-link').first().waitFor();
  await page.setViewportSize({width:390,height:844});
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth+1));
  await page.getByRole('link',{name:'Обзор',exact:true}).click();
  await page.screenshot({path:'data/mvp-mobile.png',fullPage:true});
  await page.setViewportSize({width:1440,height:1100});
  await page.screenshot({path:'data/mvp-desktop.png',fullPage:true});
  // Leave enough time for the bulk-exit interaction under concurrent feed load.
  const beforeBulkDemo=await(await page.request.get(`http://127.0.0.1:${port}/api/state?source=demo`)).json();
  const previousTradeIds=beforeBulkDemo.state.trades.map(t=>t.id);
  await page.locator('[data-scenario="delayed"]').click();
  const demoResponse=page.waitForResponse(r=>r.request().method()==='POST'&&r.url().endsWith('/api/command')&&r.request().postDataJSON()?.action==='demo');
  await page.getByTestId('run-demo').click();
  assert.equal((await demoResponse).status(),200);
  await page.waitForFunction(async ids=>{const s=await(await fetch('/api/state?source=demo')).json();return s.state.trades.some(t=>!ids.includes(t.id)&&t.status==='OPEN');},previousTradeIds,{timeout:15000});
  await page.getByRole('link',{name:'Сделки',exact:true}).click();
  const bulkResponse=page.waitForResponse(r=>r.request().method()==='POST'&&r.url().endsWith('/api/command')&&r.request().postDataJSON()?.action==='close-all');
  await page.getByRole('button',{name:'Закрыть все сделки',exact:true}).click();
  assert.equal((await bulkResponse).status(),200);
  await page.waitForFunction(()=>document.querySelector('#toast')?.textContent?.includes('Осталось открытых: 0'));
  const closedState=await(await page.request.get(`http://127.0.0.1:${port}/api/state?source=demo`)).json();
  assert.equal(closedState.state.running,false);assert.equal(closedState.metrics.openTrades,0);
  assert.ok(closedState.state.trades.some(t=>t.status==='CLOSED'),JSON.stringify(closedState.state.trades.map(t=>({status:t.status,signalAt:t.signalAt,closedAt:t.closedAt}))));
  const sortPnl=page.locator('[data-trade-sort="realizedPnl"]');
  await sortPnl.click();
  const readPnl=()=>page.locator('tbody tr').evaluateAll(rows=>rows.map(row=>Number(row.cells[5].textContent.replace(/[^0-9.-]/g,''))));
  let pnls=await readPnl();assert.ok(pnls.every((v,i)=>!i||pnls[i-1]>=v));
  await sortPnl.click();pnls=await readPnl();assert.ok(pnls.every((v,i)=>!i||pnls[i-1]<=v));
  assert.equal(await page.locator('th[aria-sort="ascending"]').count(),1);
  await page.getByRole('link',{name:'Параметры стратегии',exact:true}).click();
  assert.equal(await page.locator('[name="lossLimit"]').isEnabled(),true);
  await page.getByRole('button',{name:'Подставить профиль $500',exact:true}).click();
  assert.equal(await page.locator('[name="initialPerVenue"]').inputValue(),'250');
  assert.equal(await page.locator('[name="maxTotalExposureUsd"]').inputValue(),'100');
  await page.getByRole('button',{name:'Подставить профиль $200',exact:true}).click();
  assert.equal(await page.locator('[name="initialPerVenue"]').inputValue(),'100');
  assert.equal(await page.locator('[name="skipManualReview"]').isChecked(),false);
  await page.getByRole('button',{name:'Сохранить параметры',exact:true}).click();
  await page.waitForFunction(()=>document.querySelector('#toast')?.textContent?.includes('сохран'));
  const profileState=await(await page.request.get(`http://127.0.0.1:${port}/api/state?source=demo`)).json();
  assert.equal(profileState.state.settings.maxUnhedgedLossUsd,'0.75');
  assert.equal(profileState.state.settings.minProfitUsd,'0.15');
  assert.equal(profileState.state.settings.skipManualReview,false);
  const diagnosticPage=await browser.newPage();
  diagnosticPage.on('pageerror',e=>errors.push(e.message));
  await diagnosticPage.route('**/api/diagnostics/execution',route=>route.fulfill({json:{available:true,status:'collecting',updatedAt:new Date().toISOString(),clock:{trusted:true},stale:true,
    usableSignals:15,minimumSignals:30,capturedSignals:17,insufficientData:true,
    table:[50,100,200,400].flatMap(latencyMs=>['post-arrival','at-arrival'].map(mode=>({latencyMs,mode,available:2,unavailable:10,unknown:5,independentHypotheticalProfit:'0.4',reasons:{'price-above-limit':10}})))}}));
  await diagnosticPage.goto(`http://127.0.0.1:${port}/#logs`);
  const diagnostics=diagnosticPage.getByTestId('execution-diagnostics');await diagnostics.waitFor();
  assert.ok((await diagnostics.textContent()).includes('15 / 30'));
  assert.ok((await diagnostics.textContent()).includes('Сводка устарела'));
  assert.equal(await diagnostics.locator('tbody tr').count(),8);
  await diagnosticPage.getByTestId('execution-profile').waitFor();
  assert.equal(await diagnostics.getByRole('link',{name:'Скачать CSV'}).getAttribute('href'),'/api/diagnostics/execution?format=csv');
  await diagnosticPage.close();
  assert.deepEqual(errors,[]);
  console.log('Browser checks passed: dashboard, demo settlement/P&L, trade detail, credential placeholders, logs, mobile layout.');
}catch(e){console.error(output);throw e;}finally{
  await browser?.close();
  if(child.exitCode===null){child.kill();await new Promise(r=>child.once('exit',r));}
  await rm(directory,{recursive:true,force:true});
}
